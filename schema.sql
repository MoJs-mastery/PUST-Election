-- 1. Departments Table
CREATE TABLE IF NOT EXISTS public.depadrments_depadrments_db (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    d_name TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 2. Candidates (Musharax) Table
CREATE TABLE IF NOT EXISTS public.musharax_musharax_db (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    m_name TEXT NOT NULL,
    m_image TEXT,
    m_email TEXT,
    m_gender TEXT,
    m_depadrments_id BIGINT REFERENCES public.depadrments_depadrments_db(id) ON DELETE SET NULL,
    m_if_allowed BOOLEAN DEFAULT TRUE,
    m_joined TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    m_username TEXT
);

-- 3. Voting IDs Table
CREATE TABLE IF NOT EXISTS public.voiteid_id_db (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    c_id TEXT NOT NULL UNIQUE,
    is_used BOOLEAN DEFAULT FALSE,
    c_created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 4. Voter Audit / Votes Cast (Codbixiye) Table
CREATE TABLE IF NOT EXISTS public.codbixiye_codbixiye_db (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    c_id_id TEXT NOT NULL,
    c_musharax_id BIGINT REFERENCES public.musharax_musharax_db(id) ON DELETE CASCADE,
    c_department_id BIGINT REFERENCES public.depadrments_depadrments_db(id) ON DELETE SET NULL,
    c_gender TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 5. Profiles / Admin Users Table
CREATE TABLE IF NOT EXISTS public.profiles (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    username TEXT,
    email TEXT,
    first_name TEXT,
    last_name TEXT,
    is_superuser BOOLEAN DEFAULT TRUE,
    date_joined TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

