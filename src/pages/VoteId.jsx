import { useEffect, useMemo, useRef, useState } from 'react'
import { supabase } from '../supabaseClient'
import { useToast } from '../toast'
import { formatDateTime } from '../utils'
import Pager from '../components/Pager.jsx'
import ConfirmDeleteModal from '../components/ConfirmDeleteModal.jsx'

export default function VoteId() {
  const { showToast } = useToast()
  const [data, setData] = useState({ all_ids: [], total_ids: 0, used_ids: 0, unused_ids: 0 })
  const [loading, setLoading] = useState(true)
  const [search, setSearch] = useState('')
  const [filter, setFilter] = useState('all')
  const [genModal, setGenModal] = useState(false)
  const [quantity, setQuantity] = useState(50)
  const [saving, setSaving] = useState(false)
  const [deleteTarget, setDeleteTarget] = useState(null)
  const [page, setPage] = useState(1)
  const PER_PAGE = 100
  const fileRef = useRef(null)

  useEffect(() => {
    loadData()
  }, [])

  useEffect(() => {
    setPage(1)
  }, [filter, search])

  async function loadData() {
    setLoading(true)
    try {
      const { data: rows, error } = await supabase
        .from('voiteid_id_db')
        .select('*')
        .order('id', { ascending: false })

      if (error) throw error

      const formatted = (rows || []).map((row) => ({
        id: row.id,
        c_id: row.c_id,
        is_used: Boolean(row.is_used),
        created_at: row.c_created_at || row.created_at,
      }))

      const usedCount = formatted.filter((x) => x.is_used).length

      setData({
        all_ids: formatted,
        total_ids: formatted.length,
        used_ids: usedCount,
        unused_ids: formatted.length - usedCount,
      })
    } catch (err) {
      setData({ all_ids: [], total_ids: 0, used_ids: 0, unused_ids: 0 })
      showToast('error', 'Koorinikiba xogta waa la waayay.')
    } finally {
      setLoading(false)
    }
  }

  const filtered = useMemo(() => {
    let list = data.all_ids
    if (filter !== 'all') list = list.filter((x) => (filter === 'used' ? x.is_used : !x.is_used))
    if (search.trim()) {
      list = list.filter((x) => (x.c_id || '').toLowerCase().includes(search.toLowerCase()))
    }
    return list
  }, [data.all_ids, filter, search])

  function generateRandomCode() {
    const chars = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789'
    let code = ''
    for (let i = 0; i < 8; i++) {
      code += chars.charAt(Math.floor(Math.random() * chars.length))
    }
    return code
  }

  async function generate() {
    if (!quantity || quantity < 1 || quantity > 1000) {
      showToast('warn', 'Tirada waa inay tahay inta u dhaxaysa 1 iyo 1000.')
      return
    }
    setSaving(true)
    try {
      const existingSet = new Set(data.all_ids.map((x) => x.c_id))
      const newItems = []

      while (newItems.length < Number(quantity)) {
        const code = generateRandomCode()
        if (!existingSet.has(code)) {
          existingSet.add(code)
          // Only send c_id — id and c_created_at are auto-generated by Supabase
          newItems.push({ c_id: code })
        }
      }

      const { error } = await supabase.from('voiteid_id_db').insert(newItems)
      if (error) throw error

      showToast('success', `${quantity} Vote ID waa la sameeyay.`)
      setGenModal(false)
      loadData()
    } catch (err) {
      showToast('error', err.message || 'Waa khalad, isku day markale.')
    } finally {
      setSaving(false)
    }
  }

  async function confirmDelete() {
    if (!deleteTarget) return
    setSaving(true)
    try {
      const { error } = await supabase
        .from('voiteid_id_db')
        .delete()
        .or(`c_id.eq.${deleteTarget},id.eq.${deleteTarget}`)

      if (error) throw error

      showToast('success', 'Vote ID waa la tirtiray.')
      setDeleteTarget(null)
      loadData()
    } catch (err) {
      showToast('error', err.message || 'Waa khalad, isku day markale.')
    } finally {
      setSaving(false)
    }
  }

  async function handleExport() {
    try {
      const exportData = filtered.map((item) => ({
        'Vote ID': item.c_id,
        'Status': item.is_used ? 'Used' : 'Available',
        'Created At': item.created_at || '',
      }))

      const csvContent =
        'data:text/csv;charset=utf-8,' +
        ['Vote ID,Status,Created At']
          .concat(exportData.map((e) => `"${e['Vote ID']}","${e['Status']}","${e['Created At']}"`))
          .join('\n')

      const encodedUri = encodeURI(csvContent)
      const link = document.createElement('a')
      link.setAttribute('href', encodedUri)
      link.setAttribute('download', `Vote_IDs_${new Date().toISOString().slice(0, 10)}.csv`)
      document.body.appendChild(link)
      link.click()
      link.remove()
      showToast('success', 'File-ka waa la soo dejiyay.')
    } catch {
      showToast('error', 'Waa khalad, isku day markale.')
    }
  }

  async function handleImportFile(e) {
    const file = e.target.files?.[0]
    if (!file) return
    setSaving(true)
    try {
      const text = await file.text()
      const lines = text.split(/\r?\n/).map((l) => l.trim()).filter(Boolean)
      const newItems = []
      const existingSet = new Set(data.all_ids.map((x) => x.c_id))
      const nowStr = new Date().toISOString()

      for (let line of lines) {
        // Strip quotes or commas if CSV
        const code = line.replace(/["',]/g, '').trim().toUpperCase()
        if (code && code !== 'VOTE ID' && code !== 'VOTE_ID' && !existingSet.has(code)) {
          existingSet.add(code)
          // Only send c_id — all other columns have DEFAULT values in Supabase
          newItems.push({ c_id: code })
        }
      }

      if (newItems.length > 0) {
        const { error } = await supabase.from('voiteid_id_db').insert(newItems)
        if (error) throw error
        showToast('success', `${newItems.length} Vote ID ayaa la soo geliyay.`)
        loadData()
      } else {
        showToast('warn', 'Ma jiro Vote ID cusub oo laga helay file-ka.')
      }
    } catch (err) {
      showToast('error', err.message || 'Khalad ayaa dhacay akhrinta file-ka.')
    } finally {
      setSaving(false)
      if (fileRef.current) fileRef.current.value = ''
    }
  }

  if (loading && !data.all_ids.length) {
    return (
      <div className="spinner-center">
        <i className="fa-solid fa-spinner fa-spin" />
      </div>
    )
  }

  const totalPages = Math.max(1, Math.ceil(filtered.length / PER_PAGE))
  const pageItems = filtered.slice((page - 1) * PER_PAGE, page * PER_PAGE)

  const total = data.total_ids || 0
  const used = data.used_ids || 0
  const unused = data.unused_ids || 0
  const util = total ? Math.round((used / total) * 100) : 0

  return (
    <div>
      <div className="page-header">
        <div>
          <h2 className="page-title">
            <i className="fa-solid fa-id-card" /> Voting IDs
          </h2>
          <p className="page-subtitle">Maamul ID-ga codbixinta — abuur, soo deji, ama soo geli.</p>
        </div>
        <button className="btn btn-primary" onClick={() => setGenModal(true)}>
          <i className="fa-solid fa-plus" /> Generate IDs
        </button>
      </div>

      <div className="stat-grid">
        <div className="stat-card">
          <div className="stat-icon indigo">
            <i className="fa-solid fa-id-badge" />
          </div>
          <div>
            <div className="stat-value">{total}</div>
            <div className="stat-label">Total IDs</div>
          </div>
        </div>
        <div className="stat-card">
          <div className="stat-icon green">
            <i className="fa-solid fa-check-to-slot" />
          </div>
          <div>
            <div className="stat-value">{used}</div>
            <div className="stat-label">Used</div>
          </div>
        </div>
        <div className="stat-card">
          <div className="stat-icon purple">
            <i className="fa-solid fa-box-open" />
          </div>
          <div>
            <div className="stat-value">{unused}</div>
            <div className="stat-label">Unused</div>
          </div>
        </div>
        <div className="stat-card">
          <div className="stat-icon amber">
            <i className="fa-solid fa-chart-line" />
          </div>
          <div>
            <div className="stat-value">{util}%</div>
            <div className="stat-label">Utilization</div>
          </div>
        </div>
      </div>

      <div className="toolbar">
        <div className="toolbar-left">
          <div className="filter-pills">
            <button className={`filter-pill ${filter === 'all' ? 'active' : ''}`} onClick={() => setFilter('all')}>
              All ({total})
            </button>
            <button className={`filter-pill ${filter === 'used' ? 'active' : ''}`} onClick={() => setFilter('used')}>
              Used ({used})
            </button>
            <button className={`filter-pill ${filter === 'unused' ? 'active' : ''}`} onClick={() => setFilter('unused')}>
              Unused ({unused})
            </button>
          </div>
        </div>
        <div className="toolbar-right">
          <div className="search-box">
            <i className="fa-solid fa-magnifying-glass" />
            <input placeholder="Search ID..." value={search} onChange={(e) => setSearch(e.target.value)} />
          </div>
          <button className="btn btn-outline" onClick={handleExport} disabled={saving}>
            <i className="fa-solid fa-file-export" /> Export
          </button>
          <button className="btn btn-outline" onClick={() => fileRef.current?.click()} disabled={saving}>
            <i className="fa-solid fa-file-import" /> Import
          </button>
          <input ref={fileRef} type="file" accept=".xlsx" style={{ display: 'none' }} onChange={handleImportFile} />
        </div>
      </div>

      <div className="section-card" style={{ padding: 0 }}>
        <div className="table-wrap">
          <table className="admin-table">
            <thead>
              <tr>
                <th>#</th>
                <th>Vote ID</th>
                <th>Status</th>
                <th>Created At</th>
                <th>Actions</th>
              </tr>
            </thead>
            <tbody>
              {pageItems.map((x, i) => (
                <tr key={x.c_id}>
                  <td>{(page - 1) * PER_PAGE + i + 1}</td>
                  <td className="cell-main" style={{ fontFamily: 'monospace', letterSpacing: 1 }}>
                    {x.c_id}
                  </td>
                  <td>
                    {x.is_used ? (
                      <span className="badge red">
                        <i className="fa-solid fa-circle" style={{ fontSize: 6 }} /> Used
                      </span>
                    ) : (
                      <span className="badge green">
                        <i className="fa-solid fa-circle" style={{ fontSize: 6 }} /> Unused
                      </span>
                    )}
                  </td>
                  <td>{formatDateTime(x.created_at)}</td>
                  <td>
                    {!x.is_used && (
                      <button className="btn btn-xs btn-danger" onClick={() => setDeleteTarget(x.c_id)}>
                        <i className="fa-solid fa-trash" />
                      </button>
                    )}
                  </td>
                </tr>
              ))}
              {!filtered.length && (
                <tr>
                  <td colSpan={5}>
                    <div className="empty-state">
                      <i className="fa-solid fa-id-card" />
                      <p>Wax ID ah lama helin.</p>
                    </div>
                  </td>
                </tr>
              )}
            </tbody>
          </table>
        </div>
        {totalPages > 1 && (
          <Pager page={page} totalPages={totalPages} onPage={setPage} total={filtered.length} pageSize={PER_PAGE} />
        )}
      </div>

      {/* Generate modal */}
      {genModal && (
        <div className="modal-overlay">
          <div className="modal-container sm">
            <div className="modal-head">
              <h3>
                <i className="fa-solid fa-wand-magic-sparkles" /> Generate IDs
              </h3>
              <button className="modal-x" onClick={() => setGenModal(false)}>
                <i className="fa-solid fa-xmark" />
              </button>
            </div>
            <div className="modal-body">
              <div className="form-group">
                <label className="form-label">
                  How many IDs? <span>*</span>
                </label>
                <input
                  className="form-input"
                  type="number"
                  min="1"
                  max="1000"
                  value={quantity}
                  onChange={(e) => setQuantity(parseInt(e.target.value) || 0)}
                />
                <p className="cell-sub">Max: 1000 IDs per batch.</p>
              </div>
            </div>
            <div className="modal-foot">
              <button className="btn btn-outline" onClick={() => setGenModal(false)}>
                Cancel
              </button>
              <button className="btn btn-primary" onClick={generate} disabled={saving}>
                <i className={`fa-solid ${saving ? 'fa-spinner fa-spin' : 'fa-wand-magic-sparkles'}`} />
                {saving ? 'Generating...' : 'Generate'}
              </button>
            </div>
          </div>
        </div>
      )}

      {deleteTarget && (
        <ConfirmDeleteModal
          title="Delete ID?"
          description="Ma hubtaa inaad tirtirayso ID-ga"
          itemName={deleteTarget}
          onCancel={() => setDeleteTarget(null)}
          onConfirm={confirmDelete}
          saving={saving}
        />
      )}
    </div>
  )
}
